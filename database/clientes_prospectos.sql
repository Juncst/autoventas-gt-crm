-- =========================================
-- 1. CLIENTES
-- =========================================

CREATE TABLE IF NOT EXISTS public.clientes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(50) UNIQUE,
    nombre varchar(150) NOT NULL,
    nit varchar(30),
    telefono varchar(30),
    correo varchar(150),
    tipo varchar(30),
    asesor varchar(100),
    estado varchar(20) DEFAULT 'Activo',
    fecha_registro timestamp DEFAULT CURRENT_TIMESTAMP,
    direccion text,
    observaciones text
);

-- =========================================
-- 2. PROSPECTOS
-- =========================================

CREATE TABLE IF NOT EXISTS public.prospectos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(50) UNIQUE,
    nombre varchar(150) NOT NULL,
    descripcion text,
    telefono varchar(30),
    correo varchar(150),
    vehiculo varchar(150),
    detalle_vehiculo varchar(200),
    asesor varchar(100),
    estado varchar(30) DEFAULT 'Nuevo',
    observaciones text,
    fecha_registro timestamp DEFAULT CURRENT_TIMESTAMP,
    precio numeric(12,2) DEFAULT 0,
    fecha_cierre timestamp
);

-- =========================================
-- 3. NOTAS DE PROSPECTOS
-- =========================================

CREATE TABLE IF NOT EXISTS public.notas_prospectos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospecto_id integer NOT NULL,
    contenido text NOT NULL,
    fecha timestamp DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT notas_prospectos_prospecto_id_fkey
        FOREIGN KEY (prospecto_id)
        REFERENCES public.prospectos(id)
        ON DELETE CASCADE
);

-- =========================================
-- 4. ACTIVIDADES DE PROSPECTOS
-- =========================================

CREATE TABLE IF NOT EXISTS public.actividades_prospectos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospecto_id integer NOT NULL,
    titulo varchar(200) NOT NULL,
    descripcion text,
    tipo varchar(50),
    fecha timestamp DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT actividades_prospectos_prospecto_id_fkey
        FOREIGN KEY (prospecto_id)
        REFERENCES public.prospectos(id)
        ON DELETE CASCADE
);
