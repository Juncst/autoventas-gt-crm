-- 1. VEHICULOS

CREATE TABLE IF NOT EXISTS public.vehiculos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(50) UNIQUE NOT NULL,
    marca varchar(100) NOT NULL,
    modelo varchar(100) NOT NULL,
    anio integer NOT NULL,
    tipo varchar(50) NOT NULL,
    motor varchar(100),
    combustible varchar(50) NOT NULL,
    transmision varchar(50) NOT NULL,
    color varchar(50),
    vin varchar(30) UNIQUE,
    condicion varchar(30) DEFAULT 'Nuevo',
    kilometraje integer DEFAULT 0,
    precio numeric(12,2) NOT NULL,
    estado varchar(30) DEFAULT 'Disponible',
    imagen_url text,
    fecha_registro timestamp DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_vehiculos_anio
        CHECK (anio >= 1886),

    CONSTRAINT chk_vehiculos_kilometraje
        CHECK (kilometraje >= 0),

    CONSTRAINT chk_vehiculos_precio
        CHECK (precio >= 0)
);


-- 2. COTIZACIONES

CREATE TABLE IF NOT EXISTS public.cotizaciones (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(50) UNIQUE NOT NULL,
    cliente_id integer NOT NULL,
    vehiculo_id integer NOT NULL,
    asesor varchar(100) NOT NULL,
    monto numeric(12,2) NOT NULL,
    estado varchar(30) DEFAULT 'Borrador',
    fecha date DEFAULT CURRENT_DATE,
    validez date DEFAULT (CURRENT_DATE + 15),
    observaciones text,

    CONSTRAINT cotizaciones_cliente_id_fkey
        FOREIGN KEY (cliente_id)
        REFERENCES public.clientes(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT cotizaciones_vehiculo_id_fkey
        FOREIGN KEY (vehiculo_id)
        REFERENCES public.vehiculos(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_cotizaciones_monto
        CHECK (monto >= 0)
);


-- 3. COTIZACION_ITEMS
-- DETALLE OPCIONAL DE LAS COTIZACIONES

CREATE TABLE IF NOT EXISTS public.cotizacion_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id integer NOT NULL,
    descripcion varchar(250) NOT NULL,
    cantidad integer DEFAULT 1,
    precio numeric(12,2) NOT NULL,

    CONSTRAINT cotizacion_items_cotizacion_id_fkey
        FOREIGN KEY (cotizacion_id)
        REFERENCES public.cotizaciones(id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT chk_cotizacion_items_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT chk_cotizacion_items_precio
        CHECK (precio >= 0)
);


-- =========================================================
-- 4. INDICES
-- =========================================================

CREATE INDEX IF NOT EXISTS idx_vehiculos_estado
    ON public.vehiculos(estado);

CREATE INDEX IF NOT EXISTS idx_vehiculos_marca
    ON public.vehiculos(marca);

CREATE INDEX IF NOT EXISTS idx_cotizaciones_cliente
    ON public.cotizaciones(cliente_id);

CREATE INDEX IF NOT EXISTS idx_cotizaciones_vehiculo
    ON public.cotizaciones(vehiculo_id);

CREATE INDEX IF NOT EXISTS idx_cotizaciones_fecha
    ON public.cotizaciones(fecha);

CREATE INDEX IF NOT EXISTS idx_cotizacion_items_cotizacion
    ON public.cotizacion_items(cotizacion_id);



